/**
 * Shared project token CSS generator.
 *
 * Mirrors the app generator in src/domain/design-system/tokens/cssExport.ts:
 * registries whose extensions.tailwind.cssExport is "tailwind-theme-overrides"
 * get the Tailwind theme override output (:root + .dark + per-collection
 * [data-wb-token-modes] blocks); everything else gets the plain :root output
 * plus the same per-collection mode blocks.
 *
 * Used by workbench-tailwind-sync.mjs and the authoring gateway
 * (workbench-authoring-core.mjs) so both write the same token CSS shape.
 */

export function buildWorkbenchProjectTokenCss(registry) {
  if (shouldBuildTailwindThemeOverrideCss(registry)) {
    const tailwindCss = buildTailwindTokenCss(registry);
    if (tailwindCss) return tailwindCss;
  }
  return buildPlainWorkbenchTokenCss(registry);
}

function shouldBuildTailwindThemeOverrideCss(registry) {
  const tailwind = registry?.extensions?.tailwind;
  return Boolean(tailwind && typeof tailwind === 'object' && tailwind.cssExport === 'tailwind-theme-overrides');
}

function buildPlainWorkbenchTokenCss(registry) {
  const declarations = new Map();
  for (const collection of registry.collections) {
    const activeMode = collection.activeMode ?? collection.modes?.[0]?.id ?? 'default';
    for (const token of collection.tokens) {
      const value = serializeTokenValue(token.values[activeMode] ?? token.values.default ?? Object.values(token.values)[0]);
      if (value === null) continue;
      declarations.set(getProjectCollectionTokenCssVariableName(collection.id, token.id), value);
    }
  }

  return [
    '/* Generated by Workbench from .workbench/tokens.json. Do not edit by hand. */',
    '',
    ...renderCssBlock(':root,\n[data-wb-token-modes]', declarations),
    ...buildWorkbenchTokenModeCssBlocks(registry),
  ].join('\n');
}

function buildWorkbenchTokenModeCssBlocks(registry) {
  const blocks = [];
  for (const collection of registry.collections) {
    if (!Array.isArray(collection.modes) || collection.modes.length <= 1) continue;
    for (const mode of collection.modes) {
      const declarations = collectSingleCollectionTokenCssDeclarations(collection, mode.id);
      blocks.push(...renderCssBlock(getTokenModeSelector(collection.id, mode.id, collection), declarations));
    }
  }
  return blocks;
}

export function buildTailwindTokenCss(registry) {
  const collection = registry.collections.find((candidate) => candidate.id === 'tailwind-theme');
  if (!collection) return '';

  const root = collectWorkbenchTokenCssDeclarations(registry, 'light');
  const dark = collectWorkbenchTokenCssDeclarations(registry, 'dark');
  for (const token of collection.tokens) {
    const cssVariable = token.extensions?.cssVariable;
    if (typeof cssVariable !== 'string') continue;
    const lightValue = serializeTokenValue(token.values.light ?? token.values.default);
    const darkValue = serializeTokenValue(token.values.dark ?? token.values.light ?? token.values.default);
    if (lightValue !== null) root.set(cssVariable, lightValue);
    if (darkValue !== null) dark.set(cssVariable, darkValue);
  }

  return [
    '/* Generated by Workbench from .workbench/tokens.json for Tailwind theme variables. Do not edit by hand. */',
    '',
    // Mirror of cssExport.ts: bridge/alias var() chains must be re-declared at
    // every token-mode scope root so nested Theme scopes re-resolve them with
    // their own mode instead of inheriting values frozen at :root.
    ...renderCssBlock(':root,\n[data-wb-token-modes]', root),
    ...renderCssBlock('.dark', dark),
    ...buildTailwindTokenModeCssBlocks(registry),
  ].join('\n');
}

function buildTailwindTokenModeCssBlocks(registry) {
  const blocks = [];
  for (const collection of registry.collections) {
    if (collection.modes.length <= 1) continue;
    for (const mode of collection.modes) {
      const declarations = collection.id === 'tailwind-theme'
        ? collectTailwindThemeModeCssDeclarations(registry, collection, mode.id)
        : collectSingleCollectionTokenCssDeclarations(collection, mode.id);
      blocks.push(...renderCssBlock(getTokenModeSelector(collection.id, mode.id, collection), declarations));
    }
  }
  return blocks;
}

function collectTailwindThemeModeCssDeclarations(registry, collection, modeId) {
  const declarations = new Map();
  for (const token of collection.tokens) {
    const cssVariable = token.extensions?.cssVariable;
    if (typeof cssVariable !== 'string') continue;
    const value = serializeTokenValue(token.values[modeId] ?? token.values.default);
    if (value !== null) declarations.set(cssVariable, value);
  }
  return declarations;
}

function collectSingleCollectionTokenCssDeclarations(collection, modeId) {
  const declarations = new Map();
  for (const token of collection.tokens) {
    const value = serializeTokenValue(token.values[modeId] ?? token.values.default);
    if (value !== null) declarations.set(getProjectCollectionTokenCssVariableName(collection.id, token.id), value);
  }
  return declarations;
}

function collectWorkbenchTokenCssDeclarations(registry, modeId) {
  const declarations = new Map();
  for (const collection of registry.collections) {
    if (collection.id === 'tailwind-theme') continue;
    const collectionModeId = getEffectiveCollectionModeId(collection, modeId);
    for (const token of collection.tokens) {
      const value = serializeTokenValue(token.values[collectionModeId] ?? token.values.default);
      if (value === null) continue;
      declarations.set(getProjectCollectionTokenCssVariableName(collection.id, token.id), value);
    }
  }
  return declarations;
}

function getEffectiveCollectionModeId(collection, requestedModeId) {
  if (collection.modes.some((mode) => mode.id === requestedModeId)) return requestedModeId;
  const normalized = normalizeCssModeName(requestedModeId);
  const named = collection.modes.find((mode) => normalizeCssModeName(mode.name) === normalized);
  return named?.id ?? collection.activeMode ?? collection.modes[0]?.id ?? 'default';
}

function normalizeCssModeName(value) {
  return String(value).trim().toLowerCase();
}

export function serializeTokenValue(value) {
  if (!value) return null;
  if (value.kind === 'ref') return `var(${getProjectCollectionTokenCssVariableName(value.collectionId, value.tokenId)})`;
  if (value.kind === 'raw') return serializeRawValue(value.value);
  return null;
}

export function getProjectCollectionTokenCssVariableName(collectionId, tokenName) {
  return `--ds-token-${sanitizeCssVariableSegment(collectionId)}-${sanitizeCssVariableSegment(tokenName)}`;
}

function sanitizeCssVariableSegment(value) {
  const sanitized = String(value).trim().replace(/[^a-zA-Z0-9_-]+/g, '-').replace(/^-+|-+$/g, '');
  return sanitized || 'token';
}

function serializeRawValue(value) {
  if (value && typeof value === 'object' && typeof value.value === 'number' && typeof value.unit === 'string') {
    return `${formatNumber(value.value)}${value.unit}`;
  }
  return String(value);
}

function formatNumber(value) {
  return Number.isInteger(value) ? String(value) : String(Number(value.toFixed(4)));
}

function renderCssBlock(selector, declarations) {
  if (declarations.size === 0) return [];
  const lines = [`${selector} {`];
  for (const [name, value] of [...declarations.entries()].sort(([left], [right]) => left.localeCompare(right))) {
    lines.push(`  ${name}: ${value};`);
  }
  lines.push('}', '');
  return lines;
}

function getTokenModeSelector(collectionId, modeId, collection) {
  const pair = `${collectionId}=${modeId}`;
  const selectors = [
    ...getCollectionCustomModeSelectors(collection, modeId),
    `[data-wb-token-modes="${escapeCssAttributeValue(pair)}"]`,
    `[data-wb-token-modes^="${escapeCssAttributeValue(`${pair};`)}"]`,
    `[data-wb-token-modes$="${escapeCssAttributeValue(`;${pair}`)}"]`,
    `[data-wb-token-modes*="${escapeCssAttributeValue(`;${pair};`)}"]`,
  ];
  return selectors.join(',\n');
}

function getCollectionCustomModeSelectors(collection, modeId) {
  const attribute = collection?.extensions?.cssExport?.modeSelectorAttribute;
  if (typeof attribute !== 'string' || !/^data-[a-zA-Z0-9_-]+$/.test(attribute)) return [];
  return [`[${attribute}="${escapeCssAttributeValue(modeId)}"]`];
}

function escapeCssAttributeValue(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}
